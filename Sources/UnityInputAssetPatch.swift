/// Version-pinned delta adds L/Aim and J/Fire to the existing Unity action map.
/// All original mouse/gamepad bindings, actions and control schemes are retained.
enum UnityInputAssetPatch {
 struct Splice {let start:Int;let end:Int;let bytes:Data}
 struct Spec {let sourceSHA256:String;let sourceLength:Int;let outputSHA256:String;let outputLength:Int;let splices:[Splice]}
 static func digest(_ data:Data)->String {SHA256.hash(data:data).map{String(format:"%02x",$0)}.joined()}
 static func apply(_ input:Data,spec:Spec=cyanbrain)throws->Data {
  guard input.count==spec.sourceLength,digest(input)==spec.sourceSHA256 else {throw LibraryError("键位适配与游戏资源版本不匹配。")}
  var previous=0
  for part in spec.splices {
   guard part.start>=previous,part.end>=part.start,part.end<=input.count else {throw LibraryError("键位适配数据无效。")}
   previous=part.end
  }
  var output=input
  for part in spec.splices.reversed() {output.replaceSubrange(part.start..<part.end,with:part.bytes)}
  guard output.count==spec.outputLength,digest(output)==spec.outputSHA256 else {throw LibraryError("键位适配资源校验失败。")}
  return output
 }
